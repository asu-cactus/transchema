# compute value ranges
def compute_range_overlap(min_1, max_1, min_2, max_2):
    try:
        overlap = (min(max_1, max_2) - max(min_1, min_2)) / (
            max(max_1, max_2) - min(min_1, min_2)
        )
    except:
        return 0
    if overlap < 0:
        return 0
    return overlap


