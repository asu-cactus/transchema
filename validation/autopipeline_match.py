def get_shape_regex(word):
    result = []
    try:
        for c in word:
            if c.isupper():
                result.append("X")
            elif c.islower():
                result.append("x")
            elif c in "0123456789":
                result.append("d")
            else:
                result.append(c)
        x1 = re.sub(r"x+", "x*", "".join(result))
        return re.sub(r"X+", "X*", x1)
    except:
        return "nan"


