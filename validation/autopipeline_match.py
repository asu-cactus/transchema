    def get_groupby_features(self, col_name_groupby_counter, col_name_value_counter):
        f1 = self.nuniques
        if self.sz > 0:
            f2 = float(self.nuniques) / float(self.sz)
        else:
            f2 = 0
        f3 = self.is_monotonic
        f4 = self.type_onehot()
        f4 = f4[:-1]
        col_name = str(self.col_name)
        f5 = 0
        f6 = 0
        f7 = 0
        f8 = 0
        vrange = 0
        # f9 = [False for i in range(len(shape_vec))]
        if self.dtype in ["int", "float", "float-int", "datetime"]:
            if self.dtype == "datetime":
                vrange = (self.value_range[1] - self.value_range[0]).days
                if isna(vrange):
                    vrange = 0
                f5 = (
                    (float(self.nuniques) / float(vrange))
                    if (vrange > 0 and not isna(vrange))
                    else 0
                )  # range
            else:
                vrange = self.value_range[1] - self.value_range[0]
                if isna(vrange):
                    vrange = 0
                f5 = (
                    (float(self.nuniques) / float(vrange))
                    if (vrange > 0 and not isna(vrange))
                    else 0
                )  # range
                f6 = self.std
                f7 = (
                    (float(self.mean - self.value_range[0]) / float(vrange))
                    if (vrange > 0 and not isna(vrange))
                    else 0
                )
                # f6 = # weather it is year
                # f7 = # weather it is month
        # elif self.dtype in ['str']:
        #    f8 = len(self.shapes)# Nshapes
        # f9 = [any([s_==s for s_ in self.shapes]) for s in shape_vec]

        # relative col position in a table: note self.total_cols_in_table should not be 0
        relative_col_pos = float(self.col_pos) / float(self.n_cols)

        # count how many times this col has been used as groupby vs. vals in other tables (except this one table)
        col_name_used_as_groupby = col_name_groupby_counter[self.col_name]
        col_name_used_as_val = col_name_value_counter[self.col_name]

        # if(self.is_grouped == True):
