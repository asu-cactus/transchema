def compare_dfs(df1, df2):
    result1 = get_hash_of_table(df1)
    result2 = get_hash_of_table(df2)
    return collections.Counter(result1) == collections.Counter(result2)


def get_hash_of_table(df):
    arr = df.to_numpy()
    arr = [id(v) for v in arr]
    return arr
    r = []
    for i in range(len(df)):
        r.append(
            reduce(
                lambda x, y: (x + 0x9E3779B97F4A7C17 + (y << 6) + (y >> 2)) ^ y,
                hash_pandas_object(df.iloc[i]),
            )
        )
    # print(r)
    return r


class TableSummary(object):
    def __init__(self, table, filename, data_index):
        self.cols = []  # list of ColumnSummary
        self.schema = [
            str(col).replace("\n", " ").strip() for col in table.columns
        ]  # list of column names
        self.filename = filename
        self.data_index = data_index

    def schema_eq(self, other):
        return len(self.schema) == len(other.schema) and all(
            [self.schema[i] == other.schema[i] for i in range(len(self.schema))]
        )

    def __str__(self):
        # return 'Table {} '.format('\n'.join([str(col) for col in self.cols]))
        return "Table {} ".format(",".join([str(col) for col in self.schema]))

    def get_na_score(self):
        sz = self.cols[0].sz
        _nas = []
        for col in self.cols:
            _nas.append(col.N_nans)
        nas = pd.Series(_nas)
        return (nas.mean(), nas.mean() / float(sz))


